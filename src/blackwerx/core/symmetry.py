"""Symmetry helpers: mirror transforms applied to drawn strokes.

Axes are named: "h" (vertical mirror, left/right), "v" (horizontal mirror,
top/bottom), "d" (main diagonal y=x), "ad" (point mirror / 180 rotation).
Selected axes are composed into the full symmetry group they generate,
so e.g. "h"+"v" produces all four quadrants. Only newly drawn stitches
are expanded; existing canvas content is untouched.

Mirror extents are the pattern's continuous coordinate span (width,
height): backstitch endpoints live on intersections 0..w, and X cells
are handled by transform_stitch's cell-corner logic, so a single affine
mirrors both kinds correctly.
"""

from __future__ import annotations

from .model import Stitch, Transform, transform_stitch

AXES = ("h", "v", "d", "ad")


def _axis_matrix(axis: str, ex: int, ey: int):
    """Affine matrix (m00,m01,m10,m11,tx,ty): p' = M.p + t."""
    if axis == "h":
        return (-1, 0, 0, 1, ex, 0)
    if axis == "v":
        return (1, 0, 0, -1, 0, ey)
    if axis == "d":
        return (0, 1, 1, 0, 0, 0)
    if axis == "ad":
        return (-1, 0, 0, -1, ex, ey)
    raise ValueError(axis)


def _compose(A, B):
    """Compose affine transforms: result applies A, then B."""
    a00, a01, a10, a11, atx, aty = A
    b00, b01, b10, b11, btx, bty = B
    return (
        b00 * a00 + b01 * a10, b00 * a01 + b01 * a11,
        b10 * a00 + b11 * a10, b10 * a01 + b11 * a11,
        b00 * atx + b01 * aty + btx, b10 * atx + b11 * aty + bty,
    )


_IDENTITY = (1, 0, 0, 1, 0, 0)


def symmetry_matrices(axes, width: int, height: int) -> list:
    """All non-identity transforms generated by ``axes`` (group closure)."""
    gens = [_axis_matrix(a, width, height) for a in (axes or ()) if a in AXES]
    if not gens:
        return []
    group = {_IDENTITY}
    work = list(gens)
    while work:
        g = work.pop()
        if g in group:
            continue
        group.add(g)
        for h in gens:
            for c in (_compose(g, h), _compose(h, g)):
                if c not in group:
                    work.append(c)
    return [m for m in group if m != _IDENTITY]


def _in_bounds(s: Stitch, width: int, height: int) -> bool:
    return all(0 <= x <= width and 0 <= y <= height
               for x, y in s.extent_points())


def orphan_stitch_keys(pattern, axes) -> set:
    """Keys of stitches missing at least one symmetry counterpart.

    While symmetry is on, editing an orphan cannot be mirrored — the
    pattern loses symmetry. Used to flag "unsafe" stitches on canvas.
    """
    mats = symmetry_matrices(axes, pattern.width, pattern.height)
    if not mats:
        return set()
    ops = [Transform(*m) for m in mats]
    out = set()
    for s in pattern.stitches.values():
        for op in ops:
            if transform_stitch(s, op).key not in pattern.stitches:
                out.add(s.key)
                break
    return out


def apply_symmetry(stitches: list[Stitch], axes,
                   width: int, height: int) -> list[Stitch]:
    """Expand source stitches into mirrored copies for the group generated
    by ``axes``. Copies falling outside the pattern are dropped."""
    mats = symmetry_matrices(axes, width, height)
    if not mats or not stitches:
        return list(stitches)
    ops = [Transform(*m) for m in mats]

    out = list(stitches)
    keys = {s.key for s in out}
    for op in ops:
        for s in stitches:
            m = transform_stitch(s, op)
            if m.key not in keys and _in_bounds(m, width, height):
                keys.add(m.key)
                out.append(m)
    return out
